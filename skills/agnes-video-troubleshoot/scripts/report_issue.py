#!/usr/bin/env python3
"""Turn a failed task into a redacted, paste-ready GitHub issue.

Standard library only. Pulls exactly what the in-app failure panel pulls
(``GET /api/tasks/{id}/diagnostics``), redacts it, writes a Markdown report under
``$AGNES_HOME/reports/`` and prints a pre-filled issue URL.

The agent never submits the issue: it has no GitHub credentials and the human
should get the last word on what is published.

Usage:
  report_issue.py <task_id> [--json] [--base URL] [--print-url-only]

Exit codes:
  0  report written and URL produced
  1  the service could not be reached / diagnostics unavailable
  2  the task does not exist

Environment:
  AGNES_VIDEO_BASE   service base (default http://127.0.0.1:8765)
  AGNES_HOME         where reports are written (default ~/.agnes-video)
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

GITHUB_REPO = "https://github.com/lcy362/agnes-video-generator"
ISSUE_BODY_MAX = 4000  # same cap as frontend/src/utils/feedback.ts

_OPENER = urllib.request.build_opener(urllib.request.ProxyHandler({}))


def http_json(base: str, path: str, timeout: float = 20.0):
    try:
        with _OPENER.open(f"{base}{path}", timeout=timeout) as resp:
            return resp.status, json.loads(resp.read().decode() or "{}")
    except urllib.error.HTTPError as e:
        return e.code, {}
    except (urllib.error.URLError, OSError, json.JSONDecodeError):
        return 0, {}


def strip_secrets(text: str) -> str:
    """Redact things that must never reach a public issue."""
    if not text:
        return ""
    home = str(Path.home())
    text = text.replace(home, "~")
    # sk-... style keys, and long opaque tokens (key/id shapes).
    text = re.sub(r"\bsk-[A-Za-z0-9_\-]{8,}", "[redacted-key]", text)
    text = re.sub(r"\b[A-Za-z0-9_\-]{32,}\b", "[redacted-token]", text)
    return text


def build_report(task: dict, diag: dict, app_version: str) -> tuple[str, str]:
    summary = diag.get("summary", {}) or {}
    task_type = summary.get("task_type") or task.get("task_type", "")
    step = summary.get("current_step") or task.get("current_step", "")
    title = f"[Bug] {task_type} {step} failed".replace("  ", " ").strip()

    logs = diag.get("error_logs", []) or []
    lines = [
        "<!-- Generated by agnes-video-generator agent skill (report_issue.py). "
        "Review before submitting; add reproduction steps and expected behaviour. -->",
        "",
        "## 版本与环境",
        f"- 应用版本：{app_version or 'unknown'}",
        f"- 任务类型：{task_type or 'unknown'}",
        f"- 失败环节：{step or 'unknown'}",
        f"- 任务状态：{summary.get('status') or task.get('status', '')}",
        f"- 创建 / 更新：{summary.get('created_at', '')} / {summary.get('updated_at', '')}",
        "- 浏览器 / 系统：<!-- optional -->",
        "",
        "## 错误信息",
        "```",
        strip_secrets(str(summary.get("current_message") or task.get("current_message") or ""))[:2000],
        "```",
    ]
    if logs:
        lines += ["", f"## 上游调用错误（{len(logs)} 条，最多 20 条）", ""]
        for entry in logs[:20]:
            lines.append(
                "- `{ts}` {model}/{api} → {err} (status={code}, retry={retry}): {msg}".format(
                    ts=entry.get("timestamp", ""),
                    model=entry.get("model_type", ""),
                    api=entry.get("api_method", ""),
                    err=entry.get("error_type", ""),
                    code=entry.get("status_code", ""),
                    retry=entry.get("retry_count", ""),
                    msg=strip_secrets(str(entry.get("error_message", "")))[:300],
                )
            )
    tb = strip_secrets(str(summary.get("error_traceback", "")))
    if tb:
        lines += ["", "## Traceback（截断）", "```", tb[:3000], "```"]
    lines += [
        "",
        "## 重试情况",
        "- 已重试次数：<!-- 0 / 1 / N -->",
        "- 重试后是否仍失败：<!-- 是 / 否 -->",
        "",
        "## 复现步骤",
        "<!-- 补充可复现的操作过程与相关配置（分辨率 / 时长 / 音色 / 是否使用参考图等） -->",
        "",
        "## 期望行为",
        "<!-- -->",
    ]
    return title, "\n".join(lines)


def issue_url(title: str, body: str) -> tuple[str, bool]:
    truncated = False
    if len(body) > ISSUE_BODY_MAX:
        body = body[:ISSUE_BODY_MAX] + "\n\n…（报告过长，已截断；完整内容见本地 reports 目录）"
        truncated = True
    query = urllib.parse.urlencode({"labels": "bug", "title": title, "body": body})
    return f"{GITHUB_REPO}/issues/new?{query}", truncated


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="Prepare a redacted GitHub issue for a failed task.")
    parser.add_argument("task_id")
    parser.add_argument("--json", action="store_true")
    parser.add_argument("--base", default=os.environ.get("AGNES_VIDEO_BASE", "http://127.0.0.1:8765"))
    parser.add_argument("--print-url-only", action="store_true")
    args = parser.parse_args(argv)

    base = args.base.rstrip("/")
    status, task = http_json(base, f"/api/tasks/{args.task_id}")
    if status == 404:
        print(f"error: task {args.task_id} not found on {base}", file=sys.stderr)
        return 2
    if status != 200:
        print(f"error: cannot read task {args.task_id} from {base} (HTTP {status})", file=sys.stderr)
        return 1

    _, cfg = http_json(base, "/api/config")
    app_version = str(cfg.get("app_version", ""))
    d_status, diag = http_json(base, f"/api/tasks/{args.task_id}/diagnostics")
    if d_status != 200:
        print(
            "error: diagnostics endpoint unavailable "
            f"(HTTP {d_status}); the service may predate v6.1",
            file=sys.stderr,
        )
        return 1

    title, body = build_report(task, diag, app_version)
    home = Path(os.environ.get("AGNES_HOME") or (Path.home() / ".agnes-video")).expanduser()
    reports = home / "reports"
    reports.mkdir(parents=True, exist_ok=True)
    report_path = reports / f"issue-{args.task_id}.md"
    report_path.write_text(f"# {title}\n\n{body}\n", encoding="utf-8")

    url, truncated = issue_url(title, body)
    if args.print_url_only:
        print(url)
        return 0
    payload = {
        "ok": True,
        "task_id": args.task_id,
        "title": title,
        "report": str(report_path),
        "url": url,
        "truncated": truncated,
        "error_logs": len(diag.get("error_logs", []) or []),
        "hints": [
            "the report is redacted (home path, key-like tokens); review it before submitting",
            "the user submits the issue — do not post on their behalf",
            "search for an existing issue first: " + GITHUB_REPO + "/issues?q=is%3Aissue",
        ],
    }
    if args.json:
        print(json.dumps(payload, ensure_ascii=False, sort_keys=True))
    else:
        print(f"report: {report_path}")
        print(f"title:  {title}")
        print(f"url:    {url}")
        if truncated:
            print("note:   body exceeded 4000 chars and was truncated in the URL")
        for hint in payload["hints"]:
            print(f"hint:   {hint}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
